  <p class="legal-eyebrow">Protection des données</p>
  <h1>Politique de confidentialité</h1>
  <p class="legal-intro">
    Cette page décrit, en termes simples, les données utilisées par Car manager et les principales
    règles applicables à leur traitement.
  </p>

  <div class="legal-content">
    <h2>1. Qui utilise et gère les données ?</h2>
    <p>
      Car manager est un outil fourni aux agences de location. Lorsqu’une agence y enregistre des
      informations sur ses clients, ses contrats ou ses véhicules, l’agence détermine les finalités
      de cette utilisation et gère les accès de ses utilisateurs. Les demandes concernant ces
      informations doivent être adressées à l’agence concernée.
    </p>
    <p>
      Les informations relatives au compte utilisateur sont utilisées pour permettre l’accès au
      service, administrer le compte et en assurer la sécurité.
    </p>

    <h2>2. Quelles données peuvent être traitées ?</h2>
    <ul>
      <li><strong>Compte utilisateur :</strong> nom, adresse e-mail, mot de passe enregistré sous forme protégée, rôle et préférences de compte ;</li>
      <li><strong>Clients et contrats :</strong> coordonnées et informations d’identité ou de permis, données de réservation, de location et de facturation saisies par l’agence ;</li>
      <li><strong>Véhicules :</strong> informations d’identification, caractéristiques, état, entretien et documents de suivi ;</li>
      <li><strong>Infractions :</strong> informations relatives au véhicule, au contrat et au conducteur, selon les données saisies par l’agence ;</li>
      <li><strong>Fonctionnement du service :</strong> données techniques nécessaires à la connexion, à la sécurité et au maintien de la session.</li>
    </ul>

    <h2>3. Pourquoi les données sont-elles utilisées ?</h2>
    <p>
      Les données sont utilisées pour fournir les fonctions de gestion demandées par l’agence,
      permettre l’authentification, gérer les comptes et les autorisations, produire les documents
      demandés, assurer la sécurité du service et diagnostiquer les problèmes techniques.
      Elles ne doivent pas être utilisées à des fins incompatibles avec ces objectifs.
    </p>

    <h2>4. Qui peut y accéder ?</h2>
    <p>
      Les données d’une agence sont accessibles aux utilisateurs autorisés de cette agence selon
      leurs permissions. Les personnes chargées de l’administration ou de la maintenance technique
      peuvent y accéder uniquement lorsque cela est nécessaire au fonctionnement, à la sécurité ou
      à l’assistance du service. Des prestataires techniques peuvent intervenir pour l’hébergement
      ou la fourniture des fonctions nécessaires à l’application.
    </p>
    <p>
      L’application n’a pas pour objectif de vendre les données personnelles à des tiers.
    </p>

    <h2>5. Durée de conservation</h2>
    <p>
      Les données sont conservées pendant la durée nécessaire à la gestion du compte et à l’utilisation
      du service. Pour les dossiers clients, contrats et autres documents de l’agence, celle-ci doit
      définir et appliquer une durée de conservation conforme à ses obligations légales et à ses besoins.
      Les durées peuvent aussi dépendre des sauvegardes techniques et des obligations applicables.
    </p>

    <h2>6. Sécurité</h2>
    <p>
      Des mesures techniques et organisationnelles sont mises en œuvre pour protéger l’accès au
      service et aux données. Chaque agence et chaque utilisateur contribuent à cette protection en
      utilisant des mots de passe confidentiels, en attribuant les permissions avec prudence et en
      retirant les accès qui ne sont plus nécessaires.
    </p>

    <h2>7. Vos droits et vos demandes</h2>
    <p>
      Selon la législation applicable, les personnes concernées peuvent disposer de droits d’accès,
      de rectification, d’effacement ou d’opposition au traitement de leurs données. Pour les données
      enregistrées par une agence, adressez votre demande à cette agence. Pour une demande liée à
      votre compte utilisateur, contactez l’administrateur de votre agence.
    </p>

    <h2>8. Mise à jour de cette politique</h2>
    <p>
      Cette politique peut être mise à jour lorsque le service ou les règles applicables évoluent.
      La version affichée sur cette page est celle qui s’applique actuellement.
    </p>

    <h2>9. Contact</h2>
    <p>
      Pour toute question concernant les données de votre dossier, contactez l’agence qui les a
      enregistrées. Pour toute question concernant votre compte Car manager, contactez son
      administrateur.
    </p>
  </div>
@endsection